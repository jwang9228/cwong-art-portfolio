import { createHmac, timingSafeEqual } from 'crypto';
import { cookies } from 'next/headers';

const SESSION_TTL_MS = 1000 * 60 * 60 * 24
const COOKIE_NAME = 'portfolio_access'

// Converts an input payload into a secure cookie (string)
const getToken = (payload: number): string => {
  const body = Buffer.from(JSON.stringify(payload)).toString('base64url');

  // create signature with base64url payload and key (session secret)
  const signature = createHmac('sha256', process.env.SESSION_SECRET)
    .update(body)
    .digest('base64url');

  // cookie is the payload and signature (period as separator, parsed when verifying)
  return `${body}.${signature}`;
}

// Verifies token signed and generated by getToken, if valid returns original payload
const verifyToken = (token: string): number | null => {
  const [body, signature] = token.split('.');
  if (!body || !signature) return null;

  // recreate the signature - since same key
  // expectation is same signature if input token is generated token
  const expectedSignature = createHmac('sha256', process.env.SESSION_SECRET)
    .update(body)
    .digest('base64url');

  // initial check: compare input and expected signature
  const inputSignatureBuff = Buffer.from(signature);
  const expectedSignatureBuff = Buffer.from(expectedSignature);
  if (inputSignatureBuff.length !== expectedSignatureBuff.length || 
    !timingSafeEqual(inputSignatureBuff, expectedSignatureBuff)) {
    return null;
  }

  try {
    const payload = JSON.parse(Buffer.from(body, 'base64url').toString('utf8'));

    return Number.isFinite(payload) ? payload : null;
  } catch {
    return null;
  }
}

export const setPortfolioAccessToken = async (): Promise<void> => {
  const cookieStore = await cookies();
  const sessionExpiration = Date.now() + SESSION_TTL_MS;
  const token = getToken(sessionExpiration);

  cookieStore.set(COOKIE_NAME, token, {
    httpOnly: true,
    secure: process.env.NODE_ENV === 'production',
    sameSite: 'lax',
    path: '/',
    maxAge: SESSION_TTL_MS / 1000
  });
}

export const isPortfolioUnlocked = async (): Promise<boolean> => {
  const cookieStore = await cookies();
  const portfolioAccessCookie = cookieStore.get(COOKIE_NAME)?.value;
  if (!portfolioAccessCookie) return false;

  const sessionExpiration = verifyToken(portfolioAccessCookie);
  if (sessionExpiration === null) return false;

  return Date.now() <= sessionExpiration;
}